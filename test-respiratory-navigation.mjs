import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {modules,sections} from './public/content.js';
const nav=readFileSync('public/respiratory-navigation.js','utf8');
const lab=readFileSync('public/ventilation-practicum.js','utf8');
const html=readFileSync('public/index.html','utf8');
const css=readFileSync('public/respiratory-navigation.css','utf8');
assert.equal(modules.length,25,'25 respiratory modules required');
assert.equal(sections.length,17,'17 sections per module required');
assert.equal(new Set(sections.map(s=>s[0])).size,17,'Section keys must be unique');
for(const asset of ['respiratory-navigation.js','respiratory-navigation.css','ventilation-practicum.js','ventilation-practicum.css'])assert.ok(html.includes('/'+asset),'Missing '+asset);
for(const name of ['resp-calendar-toggle','resp-calendar','resp-progress-summary','resp-complete-checkbox'])assert.ok(nav.includes(name),'Missing navigation control '+name);
assert.ok(!nav.includes('resp-live-clock'),'Existing clock must not be duplicated');
assert.ok(nav.includes('localStorage.setItem'),'Progress must persist');
assert.ok(nav.includes('validProgressKeys'),'Progress count must reject unknown keys');
assert.ok(css.includes('@media'),'Mobile styles required');
for(const id of ['resp-vt','resp-rate','resp-dead','resp-ve','resp-va','resp-eff'])assert.ok(lab.includes(id),'Missing practicum element '+id);
for(const language of ['Минутная вентиляция','Minute ventilation','Минуттық вентиляция'])assert.ok(lab.includes(language),'Missing practicum translation '+language);
const calculate=(vt,rate,dead)=>({ve:vt*rate/1000,va:(vt-dead)*rate/1000});
assert.deepEqual(calculate(500,12,150),{ve:6,va:4.2});
assert.deepEqual(calculate(300,20,150),{ve:6,va:3});
assert.ok(lab.includes('OpenStax'),'Practicum requires source');
console.log('Respiratory navigation and ventilation regression assertions passed.');
